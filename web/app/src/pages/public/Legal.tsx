const ORDER = ["offer", "privacy", "risks", "tax"] as const;

export default function Legal() {
  const { doc = "" } = useParams();
  const { config } = useSession();
  const d = DOCS[doc];
  useTitle(d?.title || "");
  if (doc === "terms") return <Navigate to="/legal/offer" replace />;
  if (!d) return <NotFound />;
  return (
    <div className="wrapx">
      <article className="legal-doc">
        <nav className="legal-tabs" aria-label="Документы">
          {ORDER.map((k) => <NavLink key={k} to={`/legal/${k}`}>{DOCS[k].tab}</NavLink>)}
        </nav>
        <h1>{d.title}</h1>
        {config?.legal_version && doc !== "tax" && <p className="small muted">Редакция от {config.legal_version.split("-").reverse().join(".")}</p>}
        {d.body}
        <p className="mt32"><Link to="/">На главную</Link></p>
      </article>
    </div>
  );
}
